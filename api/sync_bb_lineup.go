var bbLessonIDPattern = regexp.MustCompile(`/cu/([A-Za-z0-9]+)`)
var bbSourceIDPattern = regexp.MustCompile(`/sources/([A-Za-z0-9]+)`)

// extractSourceID pulls the kabbalahmedia catalog ID out of a source URL
// (e.g. ".../sources/cQYbzWhd" or ".../he/sources/hwh1BLAL?page=50") — the ID
// needed to fetch that source's title in other languages.
func extractSourceID(link string) string {
	m := bbSourceIDPattern.FindStringSubmatch(link)
	if len(m) == 2 {
		return m[1]
	}
	return ""
}

// extractLessonID pulls the kabbalahmedia catalog ID out of a lesson URL
// (e.g. ".../lessons/cu/sRuRCtv5?..." or ".../events/cu/5yMbVH0V") — used to
// recognize when an existing, manually-created part already covers the exact
// same lesson bb-lineup is now pointing to.
func extractLessonID(link string) string {
	m := bbLessonIDPattern.FindStringSubmatch(link)
	if len(m) == 2 {
		return m[1]
	}
	return ""
}

// bbAdoptionKey returns the existingByEventLesson lookup key for a content
// item, or "" if there's no reliable way to match it against a pre-existing
// manually-created part. Lesson-linked content matches by lesson ID;
// lesson_preparation (which never has a link) matches by the event's one
// PartNumber-0 slot instead.
func bbAdoptionKey(eventID, slotType, lessonLink, lang string) string {
	if lid := extractLessonID(lessonLink); lid != "" {
		return eventID + "|" + lid + "|" + lang
	}
	if slotType == "lesson_preparation" {
		return eventID + "|prep|" + lang
	}
	return ""
}

// bbLineupHorizonBackDays/ForwardDays bound how much of the calendar this sync
// rescans on every run: recent past (bb-lineup content is sometimes finalized
// a little late) through the same forward horizon used for regular events.
const (
	bbLineupHorizonBackDays    = 30
	bbLineupHorizonForwardDays = 30
)

